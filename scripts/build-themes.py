#!/usr/bin/env python3
"""Generate the dark-mode SVGs in assets/dark/ from the light sources in assets/.

Each source SVG keeps all of its colours in one block inside <style>:

    /* palette:start */
    :root { --bg: #F4EFE6; --ink: #181818; ... }
    /* palette:end */

This script swaps every variable in that block for its DARK value and writes the
result to assets/dark/<same name>.svg. Everything else is copied untouched, so
the light file stays the single source of truth.

It also refuses to build if a source hardcodes a colour outside the palette
block (a fill/stroke/color written as a hex or rgb() value), because that colour
would not change in dark mode.

Finally it stacks the full-width strips listed in compose.py into one seamless
SVG per theme: assets/composed/profile.svg and assets/composed/dark/profile.svg.

Usage:
    python3 scripts/build-themes.py           # regenerate assets/dark/ and assets/composed/
    python3 scripts/build-themes.py --check   # exit 1 if either is stale (for CI)
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "assets"
OUT_DIR = SRC_DIR / "dark"
COMPOSED_DIR = SRC_DIR / "composed"

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compose  # noqa: E402  (scripts/compose.py)

# Dark values for every colour role. Sampled from Reference-dark.png.
DARK = {
    "bg": "#12110F",         # warm near-black canvas
    "ink": "#F4EFE6",        # line art and text invert to cream
    "accent": "#FF4E42",     # coral is identical in both themes
    "accent-hi": "#FF766B",
    "muted": "#6B665E",      # inactive tracks, a little darker than light mode's
    "faint": "#2A2824",      # empty contribution cells, just above the canvas
    "shade": "#12110F",      # mountain shadow faces stay dark
    "snow": "#F4EFE6",       # ridge highlights stay cream
    "fur": "#F4EFE6",        # panda face never inverts
    "fur-ink": "#181818",    # panda patches never invert
}

PALETTE_RE = re.compile(r"/\* palette:start \*/(.*?)/\* palette:end \*/", re.S)
VAR_RE = re.compile(r"(--([\w-]+)\s*:\s*)([^;]+)(;)")
HARDCODED_RE = re.compile(
    r"""\b(fill|stroke|stop-color|flood-color|color)\s*[:=]\s*["']?\s*(#[0-9A-Fa-f]{3,8}\b|rgba?\(|hsla?\()"""
)
HEADER = "<!-- GENERATED by scripts/build-themes.py from ../{name}. Do not edit; edit the light file and rebuild. -->\n"


def build(path):
    """Return (dark_svg_text, errors) for one light source file."""
    src = path.read_text(encoding="utf-8")
    errors = []

    blocks = list(PALETTE_RE.finditer(src))
    if len(blocks) != 1:
        return None, [f"{path.name}: expected exactly one palette block, found {len(blocks)}"]
    block = blocks[0]

    # Any colour outside the palette block would not follow the theme.
    outside = src[: block.start()] + " " * (block.end() - block.start()) + src[block.end():]
    for m in HARDCODED_RE.finditer(outside):
        line = outside.count("\n", 0, m.start()) + 1
        errors.append(f"{path.name}:{line}: hardcoded colour '{m.group(0)}' (use a palette role class instead)")

    def swap(m):
        name = m.group(2)
        if name not in DARK:
            errors.append(f"{path.name}: palette variable --{name} has no DARK value in build-themes.py")
            return m.group(0)
        return m.group(1) + DARK[name] + m.group(4)

    dark_block = VAR_RE.sub(swap, block.group(0))
    out = HEADER.format(name=path.name) + src[: block.start()] + dark_block + src[block.end():]

    for label, text in (("source", src), ("output", out)):
        try:
            ET.fromstring(text)
        except ET.ParseError as e:
            errors.append(f"{path.name}: {label} is not valid XML ({e})")

    return out, errors


def main():
    check = "--check" in sys.argv[1:]
    sources = sorted(SRC_DIR.glob("*.svg"))
    errors, stale = [], []
    dark_texts = {}  # expected dark output per source, so the composite can be built even in --check mode

    for path in sources:
        out, errs = build(path)
        errors += errs
        if errs:
            continue
        dark_texts[path.name] = out
        target = OUT_DIR / path.name
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == out:
            continue
        if check:
            stale.append(target.relative_to(ROOT))
        else:
            OUT_DIR.mkdir(exist_ok=True)
            target.write_text(out, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)}")

    # Dark files whose light source no longer exists.
    names = {p.name for p in sources}
    orphans = [p for p in OUT_DIR.glob("*.svg") if p.name not in names] if OUT_DIR.exists() else []
    for p in orphans:
        if check:
            stale.append(p.relative_to(ROOT))
        else:
            p.unlink()
            print(f"removed {p.relative_to(ROOT)}")

    # The stacked full-width strips, merged into one seamless SVG per theme (see compose.py).
    if not errors:
        themes = [
            (COMPOSED_DIR, lambda name: (SRC_DIR / name).read_text(encoding="utf-8")),
            (COMPOSED_DIR / "dark", lambda name: dark_texts[name]),
        ]
        for out_dir, read in themes:
            out = compose.compose(read)
            try:
                ET.fromstring(out)
            except ET.ParseError as e:
                errors.append(f"{compose.OUT_NAME}: composed output is not valid XML ({e})")
                continue
            target = out_dir / compose.OUT_NAME
            if target.exists() and target.read_text(encoding="utf-8") == out:
                continue
            if check:
                stale.append(target.relative_to(ROOT))
            else:
                out_dir.mkdir(parents=True, exist_ok=True)
                target.write_text(out, encoding="utf-8")
                print(f"wrote {target.relative_to(ROOT)}")

    for e in errors:
        print("error:", e, file=sys.stderr)
    for s in stale:
        print(f"stale: {s} (run python3 scripts/build-themes.py)", file=sys.stderr)
    if errors or stale:
        sys.exit(1)
    if check:
        print("assets/dark/ and assets/composed/ are up to date")


if __name__ == "__main__":
    main()
