#!/usr/bin/env python3
"""Build the FEATURED_PROJECTS section from projects.md.

Reads projects.md (see the format notes at its top) and writes:

    assets/projects-header.svg     FEATURED_PROJECTS ──── VIEW ALL →  (linked to "view all")
    assets/project-<slug>.svg      one card per project
    README.md                      the block between <!-- projects:start --> and <!-- projects:end -->

then runs build-themes.py so the dark twins in assets/dark/ stay in sync.

Each card is its own linked image, so every card is clickable. A row of three is cut
like the bentos above it: the outer cards carry the 50-unit page margin and the gaps
are 12 units, so the three images add up to exactly 100% with no whitespace between
them and the cards line up with the windows above. Rows of two or one are centred.
Cards have no canvas behind them, so they sit on GitHub's page colour like the
LET'S_CONNECT buttons (no seams to worry about).

Usage:
    python3 scripts/build-projects.py
"""

import html
import re
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "projects.md"
ASSETS = ROOT / "assets"
README = ROOT / "README.md"
GENERATED = "<!-- GENERATED by scripts/build-projects.py from projects.md. Edit projects.md, not this file. -->"

# Layout in 1000-unit page coordinates (same grid as the windows above).
CARD_W = 292
SLICES = {  # slice type -> (image width, card x inside it)
    "left": (348, 50),
    "middle": (304, 6),
    "right": (348, 6),
}
ROW_SLICES = {3: ["left", "middle", "right"], 2: ["left", "right"], 1: ["middle"]}

# Text metrics. Monospace glyphs advance ~0.6em; wrapping keeps ~10% slack for wider OS fonts.
PAD = 18
TITLE_PX, TITLE_ADV = 17, 10.2
DESC_PX, DESC_LINE, DESC_CHARS = 13, 18, 29
TAG_PX, TAG_ADV, TAG_PAD, TAG_GAP, TAG_H = 11.5, 6.9, 18, 8, 22
MAX_TITLE, MAX_LINES = 20, 3
INNER = CARD_W - 2 * PAD

FONT = "ui-monospace, 'Cascadia Code', 'Source Code Pro', Menlo, Consolas, 'Courier New', monospace"


# ---------- projects.md ----------

def parse():
    """Return (view_all_url, [project dicts]) or exit with every problem found."""
    text = re.sub(r"<!--.*?-->", "", DATA.read_text(encoding="utf-8"), flags=re.S)
    view_all, projects, errors = None, [], []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("# "):
            continue
        if line.startswith("## "):
            projects.append({"name": line[3:].strip(), "line": n})
            continue
        m = re.match(r"^-?\s*([A-Za-z ]+):\s*(.*)$", line)
        if not m:
            errors.append(f"projects.md:{n}: can't read this line: {raw!r}")
            continue
        key, value = m.group(1).strip().lower(), m.group(2).strip()
        if key == "view all" and not projects:
            view_all = value
        elif projects and key in ("link", "description", "tags"):
            projects[-1][key] = value
        else:
            errors.append(f"projects.md:{n}: unknown field {key!r} (expected link, description or tags)")

    if not projects:
        errors.append("projects.md: no projects found (each starts with a '## Name' line)")
    for p in projects:
        where = f"projects.md:{p['line']} ({p['name']})"
        if len(p["name"]) > MAX_TITLE:
            errors.append(f"{where}: name is {len(p['name'])} characters; max {MAX_TITLE}")
        if not p.get("description"):
            errors.append(f"{where}: missing '- description:'")
        link = p.get("link", "")
        if link and not re.match(r"^(https?://|mailto:)", link):
            errors.append(f"{where}: link must start with https:// (or be empty for a 'coming soon' card)")
        p["link"] = link
        p["tags"] = [t.strip() for t in p.get("tags", "").split(",") if t.strip()]
        p["lines"] = wrap(p.get("description", ""))
        if len(p["lines"]) > MAX_LINES:
            errors.append(f"{where}: description wraps to {len(p['lines'])} lines; max {MAX_LINES} (about {MAX_LINES * DESC_CHARS} characters)")
        tags_w = sum(tag_width(t) for t in p["tags"]) + TAG_GAP * max(len(p["tags"]) - 1, 0)
        if tags_w > INNER:
            errors.append(f"{where}: tags don't fit on one row ({tags_w:.0f} of {INNER} units); use fewer or shorter tags")
    if view_all and not view_all.startswith("https://"):
        errors.append("projects.md: 'view all' must be an https:// link")
    if errors:
        sys.exit("\n".join(errors))
    return view_all, projects


def wrap(text):
    lines, line = [], ""
    for word in text.split():
        while len(word) > DESC_CHARS:  # hard-split words that can't fit on any line
            if line:
                lines.append(line)
                line = ""
            lines.append(word[:DESC_CHARS])
            word = word[DESC_CHARS:]
        candidate = f"{line} {word}".strip()
        if len(candidate) <= DESC_CHARS:
            line = candidate
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def tag_width(tag):
    return len(tag) * TAG_ADV + TAG_PAD


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


# ---------- SVG ----------

def style(extra_css):
    return f"""    <style>
      /* palette:start */
      :root {{
        --bg: #F4EFE6;
        --ink: #181818;
        --faint: #DDD7CC;
        --muted: #7A756C;
      }}
      /* palette:end */

      .bg {{ fill: var(--bg); }}
      .ink {{ fill: var(--ink); }}
      .faint {{ fill: var(--faint); }}
      .muted {{ fill: var(--muted); }}
      .st-ink {{ stroke: var(--ink); }}
      .st-muted {{ stroke: var(--muted); }}
{extra_css}
      @media (prefers-reduced-motion: reduce) {{
        * {{ animation: none !important; }}
      }}
    </style>"""


def header_svg():
    css = f"""
      .h-title {{ font-family: {FONT}; font-weight: 800; font-size: 18px; letter-spacing: 1px; }}
      .h-link {{ font-family: {FONT}; font-weight: 700; font-size: 11.5px; letter-spacing: 1px; }}

      /* 90s pixel-art motion: the VIEW ALL arrow hops 2px right on a hard frame cut */
      @keyframes arrow-hop {{ 0% {{ transform: translateX(0px); }} 50%, 100% {{ transform: translateX(2px); }} }}
      .hop {{ animation: arrow-hop 1.2s steps(1, end) infinite; }}"""
    return f"""{GENERATED}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 56" width="100%" height="100%">
  <!-- No canvas behind it: the section sits on GitHub's page colour, like the LET'S_CONNECT buttons. -->
  <defs>
{style(css)}
  </defs>

  <!-- Folder Icon (matching the bento windows) -->
  <g transform="translate(50, 18) scale(1.1)">
    <path class="st-ink" d="M 1,3.5 C 1,2.3 1.9,1.5 3.1,1.5 L 8.2,1.5 L 10.5,4.2 L 18.4,4.2 C 19.6,4.2 20.5,5.1 20.5,6.3 L 20.5,14.2 C 20.5,15.4 19.6,16.3 18.4,16.3 L 3.1,16.3 C 1.9,16.3 1,15.4 1,14.2 Z"
          fill="none" stroke-width="2.2" stroke-linejoin="round" />
  </g>
  <text x="84" y="35" class="h-title ink" textLength="200" lengthAdjust="spacingAndGlyphs">FEATURED_PROJECTS</text>

  <!-- Rule -->
  <line x1="300" y1="29" x2="824" y2="29" class="st-ink" stroke-width="1.5" shape-rendering="crispEdges" />

  <!-- VIEW ALL → (the whole strip links to "view all" in projects.md) -->
  <text x="838" y="33" class="h-link ink" textLength="62" lengthAdjust="spacingAndGlyphs">VIEW ALL</text>
  <g class="hop">
    <g fill="none" class="st-ink" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
      <line x1="906" y1="29" x2="918" y2="29" />
      <polyline points="913.5,24.5 918,29 913.5,33.5" />
    </g>
  </g>

  <!-- Two Window Dots -->
  <circle cx="934" cy="29" r="3.1" class="bg st-ink" stroke-width="2.2" />
  <circle cx="946" cy="29" r="3.1" class="bg st-ink" stroke-width="2.2" />
</svg>
"""


def card_svg(p, kind, height, index):
    width, cx = SLICES[kind]
    linked = bool(p["link"])
    tone, stroke = ("ink", "st-ink") if linked else ("muted", "st-muted")
    title_len = round(len(p["name"]) * TITLE_ADV, 1)
    css = f"""
      .title {{ font-family: {FONT}; font-weight: 800; font-size: {TITLE_PX}px; }}
      .desc {{ font-family: {FONT}; font-weight: 500; font-size: {DESC_PX}px; }}
      .tag {{ font-family: {FONT}; font-weight: 500; font-size: {TAG_PX}px; text-anchor: middle; }}
      .soon {{ font-family: {FONT}; font-weight: 700; font-size: 10px; letter-spacing: 1px; text-anchor: end; }}

      /* 90s pixel-art motion: the link arrow hops up-right on a hard frame cut, staggered per card */
      @keyframes arrow-hop {{ 0% {{ transform: translate(0px, 0px); }} 50%, 100% {{ transform: translate(1px, -1px); }} }}
      .hop {{ animation: arrow-hop 1.6s steps(1, end) {index * 0.4:g}s infinite; }}"""

    frame = (f'<rect x="1.1" y="1.1" width="{CARD_W - 2.2:g}" height="{height - 6.2:g}" rx="6" ry="6" class="bg {stroke}" stroke-width="2.2" />'
             if linked else
             f'<rect x="1" y="1" width="{CARD_W - 2}" height="{height - 6}" rx="6" ry="6" class="bg {stroke}" stroke-width="2" stroke-dasharray="6 4" />')

    if linked:  # external-link icon right after the title
        ix = PAD + title_len + 9
        marker = f"""
    <!-- External Link Icon -->
    <g transform="translate({ix:g}, 18)" fill="none" class="st-ink" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
      <path d="M 6,1.5 H 1.5 V 12.5 H 12.5 V 8" />
      <g class="hop">
        <line x1="6.5" y1="7.5" x2="12.5" y2="1.5" />
        <polyline points="8.5,1.5 12.5,1.5 12.5,5.5" />
      </g>
    </g>"""
    else:
        marker = f'\n    <text x="{CARD_W - PAD}" y="31" class="soon muted">SOON</text>'

    desc = "\n".join(
        f'    <text x="{PAD}" y="{56 + DESC_LINE * i}" class="desc {tone}">{escape(line)}</text>'
        for i, line in enumerate(p["lines"])
    )

    pills, x, ty = [], PAD, height - 6 - 16 - TAG_H
    for t in p["tags"]:
        w = tag_width(t)
        pills.append(
            f'    <rect x="{x:g}" y="{ty}" width="{w:g}" height="{TAG_H}" rx="5" ry="5" class="faint" />\n'
            f'    <text x="{x + w / 2:g}" y="{ty + 15}" class="tag {tone}" textLength="{len(t) * TAG_ADV:g}" lengthAdjust="spacingAndGlyphs">{escape(t)}</text>'
        )
        x += w + TAG_GAP

    return f"""{GENERATED}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="100%" height="100%">
  <!-- Project card ({"linked from README.md" if linked else "not linked yet: dashed and muted"}).
       {kind} slice: the card sits at x {cx} of a {width}-unit image so a row of three lines up with the windows above.
       No canvas behind it, so it sits on GitHub's page colour. -->
  <defs>
{style(css)}
  </defs>

  <g transform="translate({cx}, 2)">
    {frame}

    <!-- Title -->
    <text x="{PAD}" y="32" class="title {tone}" textLength="{title_len:g}" lengthAdjust="spacingAndGlyphs">{escape(p["name"])}</text>{marker}

    <!-- Description -->
{desc}

    <!-- Tags -->
{chr(10).join(pills)}
  </g>
</svg>
"""


# ---------- README ----------

def picture(name, width, alt):
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="./assets/dark/{name}" />'
            f'<img src="./assets/{name}" width="{width}" alt="{html.escape(alt, quote=True)}" /></picture>')


def readme_block(view_all, rows):
    header = picture("projects-header.svg", "100%", "Featured projects: view all repositories")
    if view_all:
        header = f'<a href="{html.escape(view_all, quote=True)}">{header}</a>'
    row_html = []
    for row in rows:
        # No whitespace between cards: a row of three is cut to add up to exactly 100%.
        row_html.append("".join(
            (f'<a href="{html.escape(p["link"], quote=True)}">{pic}</a>' if p["link"] else pic)
            for p, pic in ((p, picture(f"project-{slug(p['name'])}.svg", f"{SLICES[kind][0] / 10:g}%",
                                        f"{p['name']}: {p['description']}" + ("" if p["link"] else " (coming soon)")))
                           for p, kind in row)
        ))
    return (
        "<!-- projects:start -->\n"
        "<!-- GENERATED by scripts/build-projects.py from projects.md. Edit projects.md, not this block. -->\n"
        f'<p align="center">\n  {header}\n</p>\n'
        f'<p align="center">\n  ' + "<br />\n  ".join(row_html) + "\n</p>\n"
        "<!-- projects:end -->"
    )


def main():
    view_all, projects = parse()

    rows = []
    for i in range(0, len(projects), 3):
        chunk = projects[i:i + 3]
        rows.append(list(zip(chunk, ROW_SLICES[len(chunk)])))

    # Every card shares one height, set by the longest description.
    lines = max(len(p["lines"]) for p in projects)
    height = 56 + DESC_LINE * (lines - 1) + 16 + TAG_H + 16 + 6

    written = {"projects-header.svg"}
    (ASSETS / "projects-header.svg").write_text(header_svg(), encoding="utf-8")
    index = 0
    for row in rows:
        for p, kind in row:
            name = f"project-{slug(p['name'])}.svg"
            (ASSETS / name).write_text(card_svg(p, kind, height, index), encoding="utf-8")
            written.add(name)
            index += 1

    # Remove cards for projects that were deleted or renamed (only files this script generated).
    for old in ASSETS.glob("project-*.svg"):
        if old.name not in written and GENERATED in old.read_text(encoding="utf-8"):
            old.unlink()
            print(f"removed assets/{old.name}")

    readme = README.read_text(encoding="utf-8")
    block = readme_block(view_all, rows)
    new, n = re.subn(r"<!-- projects:start -->.*?<!-- projects:end -->", lambda _: block, readme, flags=re.S)
    if n != 1:
        sys.exit("README.md: expected exactly one <!-- projects:start --> ... <!-- projects:end --> block")
    if new != readme:
        README.write_text(new, encoding="utf-8")
        print("updated README.md")
    print(f"built {len(projects)} project card(s) in {len(rows)} row(s)")

    subprocess.run([sys.executable, str(ROOT / "scripts" / "build-themes.py")], check=True)


if __name__ == "__main__":
    main()
