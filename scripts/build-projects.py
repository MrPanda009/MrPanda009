#!/usr/bin/env python3
"""Build the FEATURED_PROJECTS section from projects.md.

Reads projects.md (see the format notes at its top) and writes:

    assets/projects-header.svg     FEATURED_PROJECTS ──── VIEW ALL →
    assets/project-<slug>.svg      one card per project

then runs build-themes.py, which makes the dark twins, wraps the cards in background
slices (scripts/sheet.py) and rewrites the README page block with their links.

Each card is its own linked image, so every card is clickable. Cards go 4 per row when
the number of projects is a multiple of 4, otherwise 3 per row (see GRIDS for each
layout's card size and text limits). A row is cut like the bentos above it: the outer
cards carry the 50-unit page margin and the gaps are 12 units, so a full row adds up to
exactly 100% and lines up with the windows above (3 per row: 348 / 304 / 348; 4 per row:
272 / 228 / 228 / 272). A short last row uses the outer slices (or the middle one for a
single card) and sheet.py centres it with background filler slices. The card SVGs have
no canvas of their own; the sheet slices supply the background.

Usage:
    python3 scripts/build-projects.py
"""

import re
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "projects.md"
ASSETS = ROOT / "assets"
GENERATED = "<!-- GENERATED by scripts/build-projects.py from projects.md. Edit projects.md, not this file. -->"

# Layout in 1000-unit page coordinates (same grid as the windows above).
PAGE_W, MARGIN, GAP = 1000, 50, 12

# Card size and text metrics per layout (cards per row). Monospace glyphs advance ~0.6em;
# wrapping keeps ~10% slack for wider OS fonts.
GRIDS = {
    # 3 per row: 292-unit cards, cut 348 / 304 / 348
    3: dict(card_w=292, pad=18, title_px=17, title_adv=10.2, max_title=20,
            desc_px=13, desc_line=18, desc_chars=29,
            tag_px=11.5, tag_adv=6.9, tag_pad=18, tag_gap=8, tag_h=22),
    # 4 per row: 216-unit cards, cut 272 / 228 / 228 / 272
    4: dict(card_w=216, pad=16, title_px=16, title_adv=9.6, max_title=16,
            desc_px=12, desc_line=16, desc_chars=23,
            tag_px=10, tag_adv=6.0, tag_pad=14, tag_gap=6, tag_h=20),
}
MAX_LINES = 3


def columns(count):
    """Cards per row: 4 when the count is a multiple of 4 (one full row of four), else 3."""
    return 4 if count % 4 == 0 else 3


def slice_box(cols, kind):
    """(image width, card x inside it) for a card slice. Outer slices carry the page margin,
    inner joins sit mid-gap, so a full row of slices adds up to exactly PAGE_W."""
    card_w = GRIDS[cols]["card_w"]
    left = MARGIN if kind == "left" else GAP / 2
    right = MARGIN if kind == "right" else GAP / 2
    return left + card_w + right, left


def row_kinds(k):
    """Slice kinds for a row of k cards. Short rows are centred by sheet.py's filler slices."""
    return ["middle"] if k == 1 else ["left"] + ["middle"] * (k - 2) + ["right"]


def layout(projects):
    """Return (cols, rows): rows is a list of [(project, slice kind), ...]."""
    cols = columns(len(projects))
    rows = [projects[i:i + cols] for i in range(0, len(projects), cols)]
    return cols, [list(zip(row, row_kinds(len(row)))) for row in rows]

FONT = "ui-monospace, 'Cascadia Code', 'Source Code Pro', Menlo, Consolas, 'Courier New', monospace"


# ---------- projects.md ----------

def parse():
    """Return (view_all_url, [project dicts]) or exit with every problem found."""
    text = re.sub(r"<!--.*?-->", "", DATA.read_text(encoding="utf-8"), flags=re.S)
    view_all, projects, errors = None, [], []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("# "):
            continue
        if line.startswith("## "):
            projects.append({"name": line[3:].strip(), "line": n})
            continue
        m = re.match(r"^-?\s*([A-Za-z ]+):\s*(.*)$", line)
        if not m:
            errors.append(f"projects.md:{n}: can't read this line: {raw!r}")
            continue
        key, value = m.group(1).strip().lower(), m.group(2).strip()
        if key == "view all" and not projects:
            view_all = value
        elif projects and key in ("link", "description", "tags"):
            projects[-1][key] = value
        else:
            errors.append(f"projects.md:{n}: unknown field {key!r} (expected link, description or tags)")

    if not projects:
        errors.append("projects.md: no projects found (each starts with a '## Name' line)")
    # The limits depend on the layout, which depends on how many projects there are.
    cols = columns(len(projects))
    g = GRIDS[cols]
    inner = g["card_w"] - 2 * g["pad"]
    for p in projects:
        where = f"projects.md:{p['line']} ({p['name']})"
        if len(p["name"]) > g["max_title"]:
            errors.append(f"{where}: name is {len(p['name'])} characters; max {g['max_title']} with {cols} cards per row")
        if not p.get("description"):
            errors.append(f"{where}: missing '- description:'")
        link = p.get("link", "")
        if link and not re.match(r"^(https?://|mailto:)", link):
            errors.append(f"{where}: link must start with https:// (or be empty for a 'coming soon' card)")
        p["link"] = link
        p["tags"] = [t.strip() for t in p.get("tags", "").split(",") if t.strip()]
        p["lines"] = wrap(p.get("description", ""), g["desc_chars"])
        if len(p["lines"]) > MAX_LINES:
            errors.append(f"{where}: description wraps to {len(p['lines'])} lines; max {MAX_LINES} "
                          f"(about {MAX_LINES * g['desc_chars']} characters with {cols} cards per row)")
        tags_w = sum(tag_width(t, g) for t in p["tags"]) + g["tag_gap"] * max(len(p["tags"]) - 1, 0)
        if tags_w > inner:
            errors.append(f"{where}: tags don't fit on one row ({tags_w:.0f} of {inner} units with {cols} cards per row); "
                          "use fewer or shorter tags")
    if view_all and not view_all.startswith("https://"):
        errors.append("projects.md: 'view all' must be an https:// link")
    if errors:
        sys.exit("\n".join(errors))
    return view_all, projects


def wrap(text, chars):
    lines, line = [], ""
    for word in text.split():
        while len(word) > chars:  # hard-split words that can't fit on any line
            if line:
                lines.append(line)
                line = ""
            lines.append(word[:chars])
            word = word[chars:]
        candidate = f"{line} {word}".strip()
        if len(candidate) <= chars:
            line = candidate
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def tag_width(tag, g):
    return len(tag) * g["tag_adv"] + g["tag_pad"]


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


# ---------- SVG ----------

def style(extra_css):
    return f"""    <style>
      /* palette:start */
      :root {{
        --bg: #F4EFE6;
        --ink: #181818;
        --faint: #DDD7CC;
        --muted: #7A756C;
      }}
      /* palette:end */

      .bg {{ fill: var(--bg); }}
      .ink {{ fill: var(--ink); }}
      .faint {{ fill: var(--faint); }}
      .muted {{ fill: var(--muted); }}
      .st-ink {{ stroke: var(--ink); }}
      .st-muted {{ stroke: var(--muted); }}
{extra_css}
      @media (prefers-reduced-motion: reduce) {{
        * {{ animation: none !important; }}
      }}
    </style>"""


def header_svg():
    css = f"""
      .h-title {{ font-family: {FONT}; font-weight: 800; font-size: 18px; letter-spacing: 1px; }}
      .h-link {{ font-family: {FONT}; font-weight: 700; font-size: 11.5px; letter-spacing: 1px; }}

      /* 90s pixel-art motion: the VIEW ALL arrow hops 2px right on a hard frame cut */
      @keyframes arrow-hop {{ 0% {{ transform: translateX(0px); }} 50%, 100% {{ transform: translateX(2px); }} }}
      .hop {{ animation: arrow-hop 1.2s steps(1, end) infinite; }}"""
    return f"""{GENERATED}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 56" width="100%" height="100%">
  <!-- No canvas behind it: the section sits on GitHub's page colour, like the LET'S_CONNECT buttons. -->
  <defs>
{style(css)}
  </defs>

  <!-- Folder Icon (matching the bento windows) -->
  <g transform="translate(50, 18) scale(1.1)">
    <path class="st-ink" d="M 1,3.5 C 1,2.3 1.9,1.5 3.1,1.5 L 8.2,1.5 L 10.5,4.2 L 18.4,4.2 C 19.6,4.2 20.5,5.1 20.5,6.3 L 20.5,14.2 C 20.5,15.4 19.6,16.3 18.4,16.3 L 3.1,16.3 C 1.9,16.3 1,15.4 1,14.2 Z"
          fill="none" stroke-width="2.2" stroke-linejoin="round" />
  </g>
  <text x="84" y="35" class="h-title ink" textLength="200" lengthAdjust="spacingAndGlyphs">FEATURED_PROJECTS</text>

  <!-- Rule -->
  <line x1="300" y1="29" x2="824" y2="29" class="st-ink" stroke-width="1.5" shape-rendering="crispEdges" />

  <!-- VIEW ALL → (the whole strip links to "view all" in projects.md) -->
  <text x="838" y="33" class="h-link ink" textLength="62" lengthAdjust="spacingAndGlyphs">VIEW ALL</text>
  <g class="hop">
    <g fill="none" class="st-ink" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
      <line x1="906" y1="29" x2="918" y2="29" />
      <polyline points="913.5,24.5 918,29 913.5,33.5" />
    </g>
  </g>

  <!-- Two Window Dots -->
  <circle cx="934" cy="29" r="3.1" class="bg st-ink" stroke-width="2.2" />
  <circle cx="946" cy="29" r="3.1" class="bg st-ink" stroke-width="2.2" />
</svg>
"""


def card_height(projects, g):
    """Every card shares one height, set by the longest description."""
    lines = max(len(p["lines"]) for p in projects)
    return 56 + g["desc_line"] * (lines - 1) + 16 + g["tag_h"] + 16 + 6


def card_svg(p, kind, height, index, cols):
    g = GRIDS[cols]
    width, cx = slice_box(cols, kind)
    card_w, pad = g["card_w"], g["pad"]
    linked = bool(p["link"])
    tone, stroke = ("ink", "st-ink") if linked else ("muted", "st-muted")
    title_len = round(len(p["name"]) * g["title_adv"], 1)
    css = f"""
      .title {{ font-family: {FONT}; font-weight: 800; font-size: {g["title_px"]}px; }}
      .desc {{ font-family: {FONT}; font-weight: 500; font-size: {g["desc_px"]}px; }}
      .tag {{ font-family: {FONT}; font-weight: 500; font-size: {g["tag_px"]}px; text-anchor: middle; }}
      .soon {{ font-family: {FONT}; font-weight: 700; font-size: 10px; letter-spacing: 1px; text-anchor: end; }}

      /* 90s pixel-art motion: the link arrow hops up-right on a hard frame cut, staggered per card */
      @keyframes arrow-hop {{ 0% {{ transform: translate(0px, 0px); }} 50%, 100% {{ transform: translate(1px, -1px); }} }}
      .hop {{ animation: arrow-hop 1.6s steps(1, end) {index * 0.4:g}s infinite; }}"""

    frame = (f'<rect x="1.1" y="1.1" width="{card_w - 2.2:g}" height="{height - 6.2:g}" rx="6" ry="6" class="bg {stroke}" stroke-width="2.2" />'
             if linked else
             f'<rect x="1" y="1" width="{card_w - 2}" height="{height - 6}" rx="6" ry="6" class="bg {stroke}" stroke-width="2" stroke-dasharray="6 4" />')

    if linked:  # external-link icon right after the title
        ix = pad + title_len + 9
        marker = f"""
    <!-- External Link Icon -->
    <g transform="translate({ix:g}, 18)" fill="none" class="st-ink" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
      <path d="M 6,1.5 H 1.5 V 12.5 H 12.5 V 8" />
      <g class="hop">
        <line x1="6.5" y1="7.5" x2="12.5" y2="1.5" />
        <polyline points="8.5,1.5 12.5,1.5 12.5,5.5" />
      </g>
    </g>"""
    else:
        marker = f'\n    <text x="{card_w - pad}" y="31" class="soon muted">SOON</text>'

    desc = "\n".join(
        f'    <text x="{pad}" y="{56 + g["desc_line"] * i}" class="desc {tone}">{escape(line)}</text>'
        for i, line in enumerate(p["lines"])
    )

    tag_h = g["tag_h"]
    pills, x, ty = [], pad, height - 6 - 16 - tag_h
    for t in p["tags"]:
        w = tag_width(t, g)
        pills.append(
            f'    <rect x="{x:g}" y="{ty}" width="{w:g}" height="{tag_h}" rx="5" ry="5" class="faint" />\n'
            f'    <text x="{x + w / 2:g}" y="{ty + round(tag_h / 2 + g["tag_px"] * 0.35, 1):g}" class="tag {tone}" '
            f'textLength="{len(t) * g["tag_adv"]:g}" lengthAdjust="spacingAndGlyphs">{escape(t)}</text>'
        )
        x += w + g["tag_gap"]

    return f"""{GENERATED}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:g} {height}" width="100%" height="100%">
  <!-- Project card ({"linked from README.md" if linked else "not linked yet: dashed and muted"}).
       {kind} slice of a {cols}-per-row layout: the card sits at x {cx:g} of a {width:g}-unit image so a full row
       lines up with the windows above. No canvas of its own: scripts/sheet.py wraps it in a background slice. -->
  <defs>
{style(css)}
  </defs>

  <g transform="translate({cx:g}, 2)">
    {frame}

    <!-- Title -->
    <text x="{pad}" y="32" class="title {tone}" textLength="{title_len:g}" lengthAdjust="spacingAndGlyphs">{escape(p["name"])}</text>{marker}

    <!-- Description -->
{desc}

    <!-- Tags -->
{chr(10).join(pills)}
  </g>
</svg>
"""


def main():
    _, projects = parse()
    cols, rows = layout(projects)
    height = card_height(projects, GRIDS[cols])

    written = {"projects-header.svg"}
    (ASSETS / "projects-header.svg").write_text(header_svg(), encoding="utf-8")
    index = 0
    for row in rows:
        for p, kind in row:
            name = f"project-{slug(p['name'])}.svg"
            (ASSETS / name).write_text(card_svg(p, kind, height, index, cols), encoding="utf-8")
            written.add(name)
            index += 1

    # Remove cards for projects that were deleted or renamed (only files this script generated).
    for old in ASSETS.glob("project-*.svg"):
        if old.name not in written and GENERATED in old.read_text(encoding="utf-8"):
            old.unlink()
            print(f"removed assets/{old.name}")

    print(f"built {len(projects)} project card(s) in {len(rows)} row(s) of up to {cols}")

    subprocess.run([sys.executable, str(ROOT / "scripts" / "build-themes.py")], check=True)


if __name__ == "__main__":
    main()
