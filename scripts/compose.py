#!/usr/bin/env python3
"""Stack the full-width strips into one SVG so the page has no image seams.

Separate stacked <img>s meet at fractional pixel positions, and on 1x screens the
browser softens each image's edge row against the page behind it, which leaves a
faint light line between strips in light mode. Inside one SVG the joins sit on a
background-coloured backdrop instead, so nothing shows through.

Each part is inlined as a nested <svg>. Its ids, classes and @keyframes names get a
per-part prefix, so the parts' styles and defs can't collide; the colour-role
variables (--bg, --ink, ...) stay shared because every part defines them identically.

Called by build-themes.py after it writes assets/dark/, for both themes:
    assets/composed/profile.svg        (from the light parts)
    assets/composed/dark/profile.svg   (from the dark parts)
"""

import re

# (source file, prefix) from top to bottom.
PARTS = [
    ("Hero-Banner.svg", "hero"),
    ("bento-about-currently.svg", "about"),
    ("bento-bottom.svg", "stats"),
]
OUT_NAME = "profile.svg"

ROOT_RE = re.compile(r"^\s*(?:<!--.*?-->\s*)*<svg\b([^>]*)>(.*)</svg>\s*$", re.S)
STYLE_RE = re.compile(r"(<style>)(.*?)(</style>)", re.S)


def namespace(svg, prefix):
    """Return (root attributes, body) with ids, classes and keyframes prefixed."""
    m = ROOT_RE.match(svg)
    if not m:
        raise ValueError(f"{prefix}: not a single root <svg> element")
    attrs, body = m.group(1), m.group(2)

    ids = set(re.findall(r'\bid="([^"]+)"', body))
    classes = {c for attr in re.findall(r'\bclass="([^"]+)"', body) for c in attr.split()}
    keyframes = set(re.findall(r"@keyframes\s+([\w-]+)", body))

    def rename_markup(text):
        text = re.sub(r'\bid="([^"]+)"', lambda t: f'id="{prefix}-{t.group(1)}"', text)
        text = re.sub(r'href="#([^"]+)"',
                      lambda t: f'href="#{prefix}-{t.group(1)}"' if t.group(1) in ids else t.group(0), text)
        text = re.sub(r"url\(#([^)]+)\)",
                      lambda t: f"url(#{prefix}-{t.group(1)})" if t.group(1) in ids else t.group(0), text)
        return re.sub(r'\bclass="([^"]+)"',
                      lambda t: 'class="%s"' % " ".join(f"{prefix}-{c}" for c in t.group(1).split()), text)

    def rename_css(css):
        # Only rename class selectors this part actually uses, so numbers like 0.6s are never touched.
        css = re.sub(r"(?<![\w-])\.([A-Za-z][\w-]*)(?![\w-])",
                     lambda t: f".{prefix}-{t.group(1)}" if t.group(1) in classes else t.group(0), css)
        css = re.sub(r"(@keyframes\s+)([\w-]+)", lambda t: f"{t.group(1)}{prefix}-{t.group(2)}", css)
        return re.sub(r"(animation(?:-name)?\s*:\s*)([\w-]+)",
                      lambda t: f"{t.group(1)}{prefix}-{t.group(2)}" if t.group(2) in keyframes else t.group(0), css)

    # Rewrite markup and CSS separately so CSS selectors aren't mistaken for markup and vice versa.
    out, last = [], 0
    for s in STYLE_RE.finditer(body):
        out.append(rename_markup(body[last:s.start()]))
        out.append(s.group(1) + rename_css(s.group(2)) + s.group(3))
        last = s.end()
    out.append(rename_markup(body[last:]))
    return attrs, "".join(out)


def compose(read):
    """Build the stacked SVG; `read(name)` returns a part's SVG text (light or dark)."""
    nested, y = [], 0
    for name, prefix in PARTS:
        attrs, body = namespace(read(name), prefix)
        vb = re.search(r'viewBox="([^"]+)"', attrs).group(1)
        width, height = (float(v) for v in vb.split()[2:])
        # Keep the part's own root attributes (e.g. the hero's shape-rendering) on its nested <svg>.
        extra = re.sub(r'\s(xmlns|viewBox|width|height)="[^"]*"', "", attrs).strip()
        nested.append(
            f'  <!-- ===== {name} ===== -->\n'
            f'  <svg x="0" y="{y:g}" width="{width:g}" height="{height:g}" viewBox="{vb}"'
            f'{" " + extra if extra else ""}>{body}</svg>'
        )
        y += height
    first = PARTS[0][1]
    return (
        f'<!-- GENERATED by scripts/compose.py from {", ".join(n for n, _ in PARTS)}. Do not edit. -->\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 {y:g}" width="100%" height="100%">\n'
        f'  <!-- Backdrop in the page colour, so the joins between parts blend into it. -->\n'
        f'  <rect width="1000" height="{y:g}" class="{first}-bg" />\n'
        + "\n".join(nested)
        + "\n</svg>\n"
    )
