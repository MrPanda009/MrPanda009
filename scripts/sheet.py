#!/usr/bin/env python3
"""Lay the whole page out as one continuous background sheet, keeping every link clickable.

The top of the page is one image (assets/composed/profile.svg, see compose.py). Below it,
the LET'S_CONNECT buttons, the FEATURED_PROJECTS header, the project cards and the footer
must stay separate images so each can be its own link. This module wraps each of them in
a background-coloured slice cut on the page grid (1000 units wide, 50-unit margins, 12-unit
gaps), so every row of slices adds up to exactly 100%. All images then go into ONE <p>
with no whitespace between them, which GitHub renders as one continuous sheet.

Known, accepted tradeoff (owner's choice): separate images meet at fractional pixel
positions, so on 1x screens in light mode about half of the joins show a faint light
hairline. Dark mode and Retina/2x screens are unaffected. The top image has no internal
joins because it is composed into one SVG.

Called by build-themes.py, which writes the slices to assets/composed/[dark/]sheet-*.svg and
the <!-- page:start --> ... <!-- page:end --> block in README.md.
"""

import html
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "<!-- GENERATED by scripts/sheet.py (via build-themes.py). Do not edit. -->"

# LET'S_CONNECT buttons, left to right: (button SVG in assets/, link or None, alt text).
# A button without a link (Portfolio) is drawn dashed and muted in its own SVG.
BUTTONS = [
    ("btn-github.svg", "https://github.com/MrPanda009", "GitHub"),
    ("btn-linkedin.svg", "https://www.linkedin.com/in/shrey-singh-70898237b/", "LinkedIn"),
    ("btn-x.svg", "https://x.com/MrPanda009w", "X (Twitter)"),
    ("btn-email.svg", "mailto:shrey33005@gmail.com", "Email"),
    ("btn-portfolio.svg", None, "Portfolio (coming soon)"),
]

PAGE_W, MARGIN, GAP = 1000, 50, 12
BTN_SRC_W, BTN_SRC_H = 176, 48      # the button SVGs' viewBox
BTN_ROW_H, BTN_TOP = 64, 8
HEADER_H, HEADER_TOP = 66, 10       # projects-header.svg is 1000 x 56
CARD_GAP_BELOW = 12
FOOTER_H, FOOTER_TOP = 124, 4       # footer.svg is 1000 x 110

TOP_ALT = ("Shrey Singh (MrPanda009): building useful things at the intersection of code, AI and real-world "
           "impact. About me, what I'm currently working on, tech stack and live GitHub stats.")

PART_RE = re.compile(r"^\s*(?:<!--.*?-->\s*)*<svg\b([^>]*)>(.*)</svg>\s*$", re.S)


class StaleParts(Exception):
    """A generated part doesn't match the current layout (e.g. cards from an older build-projects run)."""


def _projects():
    spec = importlib.util.spec_from_file_location("build_projects", ROOT / "scripts" / "build-projects.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _viewbox(svg):
    return [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]


def plan(read):
    """Return (cells, view_all): every slice in page order. read(name) gives a light part's SVG text."""
    bp = _projects()
    view_all, projects = bp.parse()
    cells = []

    # Buttons: equal widths spanning the window grid (x 50..950) with 12-unit gaps.
    n = len(BUTTONS)
    btn_w = (PAGE_W - 2 * MARGIN - GAP * (n - 1)) / n
    btn_h = BTN_SRC_H * btn_w / BTN_SRC_W
    for i, (name, link, alt) in enumerate(BUTTONS):
        left = MARGIN if i == 0 else GAP / 2
        right = MARGIN if i == n - 1 else GAP / 2
        cells.append(dict(out=f"sheet-{name}", w=left + btn_w + right, h=BTN_ROW_H,
                          part=(name, left, BTN_TOP, btn_w, btn_h), link=link, alt=alt))

    cells.append(dict(out="sheet-projects-header.svg", w=PAGE_W, h=HEADER_H,
                      part=("projects-header.svg", 0, HEADER_TOP, PAGE_W, 56),
                      link=view_all, alt="Featured projects: view all repositories"))

    # Project cards: build-projects.py already cut each card on the grid
    # (3 per row: 348 / 304 / 348; 4 per row: 272 / 228 / 228 / 272).
    cols, rows = bp.layout(projects)
    for row in rows:
        names = [f"project-{bp.slug(p['name'])}.svg" for p, _ in row]
        sizes = [_viewbox(read(nm))[2:] for nm in names]
        for nm, (p, kind), (w, _) in zip(names, row, sizes):
            expected = bp.slice_box(cols, kind)[0]
            if abs(w - expected) > 0.01:  # cards built for a different layout would be squeezed into the wrong slots
                raise StaleParts(f"{nm} is {w:g} units wide but the {cols}-per-row layout needs {expected:g}")
        h = max(s[1] for s in sizes) + CARD_GAP_BELOW
        fill = (PAGE_W - sum(s[0] for s in sizes)) / 2
        filler = dict(out=f"sheet-fill-{fill:g}x{h:g}.svg", w=fill, h=h, part=None, link=None, alt="")
        if fill > 0:
            cells.append(filler)
        for (p, _), nm, (w, ph) in zip(row, names, sizes):
            cells.append(dict(out=f"sheet-{nm}", w=w, h=h, part=(nm, 0, 0, w, ph), link=p["link"] or None,
                              alt=f"{p['name']}: {p['description']}" + ("" if p["link"] else " (coming soon)")))
        if fill > 0:
            cells.append(dict(filler))

    cells.append(dict(out="sheet-footer.svg", w=PAGE_W, h=FOOTER_H,
                      part=("footer.svg", 0, FOOTER_TOP, PAGE_W, 110), link=None,
                      alt="Exploring ideas. Shipping projects. Learning always."))
    return cells


def bg_colour(read):
    """The sheet colour, taken from the hero's palette in that theme (no hardcoded value)."""
    return re.search(r"--bg:\s*(#[0-9A-Fa-f]{6})", read("Hero-Banner.svg")).group(1)


def render(cell, read, bg):
    w, h = cell["w"], cell["h"]
    nested = ""
    if cell["part"]:
        name, x, y, pw, ph = cell["part"]
        m = PART_RE.match(read(name))
        attrs, body = m.group(1), m.group(2)
        vb = re.search(r'viewBox="([^"]+)"', attrs).group(1)
        extra = re.sub(r'\s(xmlns|viewBox|width|height)="[^"]*"', "", attrs).strip()
        nested = (f'\n  <!-- {name} -->\n  <svg x="{x:g}" y="{y:g}" width="{pw:g}" height="{ph:g}" viewBox="{vb}"'
                  f'{" " + extra if extra else ""}>{body}</svg>')
    return (f"{GENERATED}\n"
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:g} {h:g}" width="100%" height="100%">\n'
            f'  <rect width="{w:g}" height="{h:g}" fill="{bg}" />{nested}\n</svg>\n')


def readme_block(cells):
    def picture(name, width, alt):
        return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="./assets/composed/dark/{name}" />'
                f'<img src="./assets/composed/{name}" width="{width}" align="top" alt="{html.escape(alt, quote=True)}" /></picture>')

    parts = [picture("profile.svg", "100%", TOP_ALT)]
    for c in cells:
        pic = picture(c["out"], f"{c['w'] / 10:g}%", c["alt"])
        parts.append(f'<a href="{html.escape(c["link"], quote=True)}">{pic}</a>' if c["link"] else pic)
    # One paragraph, no whitespace anywhere between images: any space would open a gap or wrap a row.
    return ("<!-- page:start -->\n"
            "<!-- GENERATED by scripts/sheet.py (via build-themes.py): the whole page as one continuous sheet.\n"
            "     Edit the parts in assets/, projects.md, or BUTTONS in scripts/sheet.py, then run build-themes.py. -->\n"
            f'<p align="center">{"".join(parts)}</p>\n'
            "<!-- page:end -->")


def build(read_light, read_dark):
    """Return ({"light": {name: svg}, "dark": {name: svg}}, readme_block)."""
    cells = plan(read_light)
    out = {"light": {}, "dark": {}}
    for theme, read in (("light", read_light), ("dark", read_dark)):
        bg = bg_colour(read)
        for c in cells:
            out[theme][c["out"]] = render(c, read, bg)
    return out, readme_block(cells)
